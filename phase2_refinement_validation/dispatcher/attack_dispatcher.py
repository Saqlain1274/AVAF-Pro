"""
===============================================================================
AVAF Pro - Attack Dispatcher

Coordinates attack execution using bounded parallel workers.

Responsibilities
----------------
- Receive every AttackVector from Phase 1.
- Use attack.supports(vector) as the compatibility filter.
- Create one job for every compatible vector/attack combination.
- Execute compatible attacks in bounded parallel workers.
- Collect AttackResult objects.
- Report progress to the GUI.

Important
---------
This does NOT limit scanning to a fixed number of vectors.

If Phase 1 produces:
    68 vectors  -> process all 68
    200 vectors -> process all 200
    500 vectors -> process all 500

The dispatcher only avoids running attacks that are incompatible
with a particular vector.

Parallelism is bounded so we do not create hundreds/thousands of
threads at once.
===============================================================================
"""

from __future__ import annotations

import logging

from concurrent.futures import (
    ThreadPoolExecutor,
    as_completed,
)

from typing import Iterable

from phase2_refinement_validation.context.attack_context import (
    AttackContext,
)

from phase2_refinement_validation.models.attack_result import (
    AttackResult,
)

from phase2_refinement_validation.models.attack_vector import (
    AttackVector,
)

from phase2_refinement_validation.registry.attack_registry import (
    AttackRegistry,
)

from phase2_refinement_validation.attacks.attack_request_builder import (
    AttackRequestBuilder,
)

from phase2_refinement_validation.refinment.executor.attack_executor import (
    AttackExecutor,
)

logger = logging.getLogger(__name__)


class AttackDispatcher:
    """
    Coordinates execution of compatible attacks.

    Every compatible vector/attack combination is considered.

    Example:

        200 vectors
             |
             v
        supports()
             |
             +---- SQLi compatible
             +---- XSS compatible
             +---- LFI compatible
             |
             v
        bounded parallel execution
             |
             v
        AttackResults
        """

    def __init__(
        self,
        registry: AttackRegistry,
        max_workers: int = 16,
    ) -> None:

        self.registry = registry

        # HTTP-bound workload:
        # more concurrency than CPU-bound Python work is useful here,
        # but keep a hard upper bound to avoid creating excessive load.
        self.max_workers = max(
            1,
            min(
                int(max_workers),
                24,
            ),
        )

    @staticmethod
    def _create_job_context(parent_context: AttackContext) -> AttackContext:
        """
        Create an isolated context for one vector/attack job.

        Never share mutable validation state between parallel jobs.
        """

        return AttackContext(
            builder=AttackRequestBuilder(),
            executor=AttackExecutor(
                timeout=parent_context.timeout,
                verify_ssl=parent_context.verify_ssl,
                connect_timeout=3.0,
                read_timeout=float(parent_context.timeout),
            ),
            original_response=parent_context.original_response,
            timeout=parent_context.timeout,
            verify_ssl=parent_context.verify_ssl,
            follow_redirects=parent_context.follow_redirects,
            scheme=parent_context.scheme,
            url=parent_context.url,
            proxies=dict(parent_context.proxies),
            metadata=dict(parent_context.metadata),
        )

    # =========================================================================
    # PUBLIC API
    # =========================================================================

    def dispatch(
        self,
        vectors: Iterable[AttackVector],
        context: AttackContext,
        progress_cb=None,
    ) -> list[AttackResult]:
        """
        Execute all compatible attacks.

        Parameters
        ----------
        vectors:
            All AttackVectors generated by Phase 1.

        context:
            Shared AttackContext.

        progress_cb:
            Optional callback receiving progress from 0-50.

        Returns
        -------
        list[AttackResult]
            Results generated by compatible attacks.
        """

        # Materialize the iterable exactly once.
        vectors = list(vectors)

        if not vectors:
            print(
                "[DISPATCHER] No vectors received.",
                flush=True,
            )
            return []

        # ---------------------------------------------------------------------
        # Load registered attack modules.
        # ---------------------------------------------------------------------

        attacks = list(
            self.registry.all()
        )

        print(
            f"[DISPATCHER] "
            f"Vectors={len(vectors)} "
            f"Attacks={len(attacks)} "
            f"Workers={self.max_workers}",
            flush=True,
        )

        # ---------------------------------------------------------------------
        # BUILD COMPATIBLE JOBS
        #
        # We do NOT discard vectors here.
        #
        # Every vector is inspected.
        #
        # supports(vector) decides which attack modules are meaningful for
        # that vector.
        # ---------------------------------------------------------------------

        jobs = []

        for vector_index, vector in enumerate(
            vectors,
            start=1,
        ):

            # A parameter-less vector cannot be actively mutated.
            if not getattr(
                vector,
                "parameter",
                None,
            ):

                print(
                    f"[DISPATCHER] "
                    f"Vector {vector_index}: "
                    f"skipped - no parameter",
                    flush=True,
                )

                continue

            compatible_attacks = []

            # ---------------------------------------------------------------
            # SMART COMPATIBILITY FILTER
            # ---------------------------------------------------------------

            for attack in attacks:

                try:

                    supported = attack.supports(
                        vector
                    )

                except Exception:

                    logger.exception(
                        "Attack '%s' supports() failed "
                        "for vector %s.",
                        getattr(
                            attack,
                            "id",
                            "unknown",
                        ),
                        vector_index,
                    )

                    continue

                if supported:
                    compatible_attacks.append(
                        attack
                    )

            print(
                f"[DISPATCHER] "
                f"Vector={vector_index} "
                f"{getattr(vector, 'method', '')} "
                f"{getattr(vector, 'url', '')} "
                f"| parameter="
                f"{getattr(vector, 'parameter', '')} "
                f"| compatible="
                f"{len(compatible_attacks)}",
                flush=True,
            )

            # ---------------------------------------------------------------
            # Create one job per compatible attack.
            # ---------------------------------------------------------------

            for attack in compatible_attacks:

                jobs.append(
                    (
                        vector_index,
                        vector,
                        attack,
                    )
                )

        total_jobs = len(jobs)

        print(
            f"[DISPATCHER] "
            f"All vectors inspected={len(vectors)} "
            f"| compatible attack jobs={total_jobs}",
            flush=True,
        )

        if total_jobs == 0:

            print(
                "[DISPATCHER] "
                "No compatible attack jobs found.",
                flush=True,
            )

            if progress_cb is not None:

                try:
                    progress_cb(50.0)

                except Exception:
                    pass

            return []

        # =========================================================================
        # PARALLEL ATTACK EXECUTION
        # =========================================================================

        results: list[AttackResult] = []

        completed_jobs = 0

        print(
            f"[DISPATCHER] Starting bounded parallel execution "
            f"with {self.max_workers} workers...",
            flush=True,
        )

        with ThreadPoolExecutor(
            max_workers=self.max_workers,
            thread_name_prefix="avaf-attack",
        ) as pool:

            futures = {}

            for (
                vector_index,
                vector,
                attack,
            ) in jobs:

                future = pool.submit(
                    self._execute_one,
                    vector_index,
                    vector,
                    attack,
                    context,
                )

                futures[future] = (
                    vector_index,
                    getattr(
                        attack,
                        "id",
                        "unknown",
                    ),
                )

            # -------------------------------------------------------------
            # Collect results as soon as each worker finishes.
            # -------------------------------------------------------------

            for future in as_completed(
                futures
            ):

                vector_index, attack_id = (
                    futures[future]
                )

                try:

                    attack_results = (
                        future.result()
                    )

                    if attack_results:

                        results.extend(
                            attack_results
                        )

                except Exception:

                    logger.exception(
                        "Attack '%s' failed "
                        "on vector %s.",
                        attack_id,
                        vector_index,
                    )

                completed_jobs += 1

                # ---------------------------------------------------------
                # Phase-2 attack progress = 0 -> 50
                # ---------------------------------------------------------

                if progress_cb is not None:

                    progress = (
                        completed_jobs
                        / total_jobs
                    ) * 50.0

                    try:

                        progress_cb(
                            progress
                        )

                    except Exception:

                        logger.debug(
                            "Progress callback failed.",
                            exc_info=True,
                        )

        # =========================================================================
        # COMPLETE
        # =========================================================================

        print(
            f"[DISPATCHER] "
            f"Dispatch complete. "
            f"Jobs={total_jobs} "
            f"Results={len(results)}",
            flush=True,
        )

        # Make sure attack phase ends at exactly 50%.
        if progress_cb is not None:

            try:
                progress_cb(50.0)

            except Exception:
                pass

        return results

    # =========================================================================
    # SINGLE ATTACK JOB
    # =========================================================================

    @staticmethod
    def _execute_one(
        vector_index: int,
        vector: AttackVector,
        attack,
        context: AttackContext,
    ) -> list[AttackResult]:
        """
        Execute one vector/attack combination.

        This method runs inside a worker thread.
        """

        attack_id = getattr(
            attack,
            "id",
            "unknown",
        )

        print(
            f"[DISPATCHER] "
            f"Vector={vector_index} "
            f"attack='{attack_id}' "
            f"started",
            flush=True,
        )

        try:

            job_context = AttackDispatcher._create_job_context(
                context
            )
            
            job_context.set(
                "vector_index",
                vector_index,
            )
            
            job_context.set(
                "attack_id",
                attack_id,
            )
            
            job_context.set(
                "vector_id",
                getattr(vector, "id", None)
                or getattr(vector, "vector_id", None)
                or f"vector-{vector_index}",
            )
            
            attack_results = attack.execute(
                vector=vector,
                context=job_context,
            )

            print(
                f"[ATTACK-RESULT-TRACE] "
                f"vector={vector_index} "
                f"attack={attack_id} "
                f"results={len(attack_results or [])}",
                flush=True,
            )

            # -------------------------------------------------------------
            # Preserve originating vector ownership.
            #
            # Every AttackResult must remain traceable to the exact
            # AttackVector that produced it.
            # -------------------------------------------------------------

            if attack_results:

                for result in attack_results:
                    print(
                        f"[ATTACK-RESULT] "
                        f"attack={getattr(result, 'attack', '')!r} "
                        f"payload={getattr(result, 'payload', '')!r} "
                        f"confidence={getattr(result, 'confidence', 0.0)!r} "
                        f"evidence={getattr(result, 'evidence', '')!r} "
                        f"indicator={getattr(result, 'indicator', '')!r}",
                        flush=True,
                    )

                    if getattr(
                        result,
                        "vector",
                        None,
                    ) is None:

                        try:
                            result.vector = vector
                        except Exception:
                            logger.warning(
                                "AttackResult from '%s' "
                                "could not retain originating vector.",
                                attack.id,
                            )

            if not attack_results:

                print(
                    f"[DISPATCHER] "
                    f"Vector={vector_index} "
                    f"attack='{attack_id}' "
                    f"finished results=0",
                    flush=True,
                )

                return []

            normalized_results = list(
                attack_results
            )

            print(
                f"[DISPATCHER] "
                f"Vector={vector_index} "
                f"attack='{attack_id}' "
                f"finished "
                f"results={len(normalized_results)}",
                flush=True,
            )

            return normalized_results

        except Exception:

            logger.exception(
                "Attack '%s' failed against vector '%s'.",
                attack_id,
                getattr(
                    vector,
                    "url",
                    "unknown",
                ),
            )

            return []
